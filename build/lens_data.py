def construct_rows(with_eba=True):
    rows = []
    for code, dom, name, csrc, _d, inds, ebas in CONSTRUCTS:
        for i, ind in enumerate(inds):
            rows.append([dom, name, ind, STAGES[i], (ebas[i] if with_eba else ""), f"{csrc}. {STAGE_SRC[i]}"])
    return rows

